-- Tests for the embedded C core exposed as tuipro.core.
local here = (arg and arg[0] or "tests/test_core.lua"):match("^(.*)/") or "."
local H = dofile(here .. "/helper.lua")
local core = H.core
local A = H.assert
local test = H.test

test("core version and initialization", function()
  A.truthy(H.t.version)
  A.eq(core.version, H.t.version)
  A.eq(core.engine, "LuaJIT")
  A.falsy(core.initialized())
  H.with_core(40, 10, function()
    A.truthy(core.initialized())
    local w, h = core.size()
    A.eq(w, 40)
    A.eq(h, 10)
    local info = core.info()
    A.eq(info.width, 40)
    A.eq(info.height, 10)
    A.eq(info.version, H.t.version)
    A.truthy(info.truecolor)
    A.eq(core.poll(0), nil)
  end)
  A.falsy(core.initialized())
end)

test("text width handles ASCII, UTF-8 and combining marks", function()
  H.with_core(20, 4, function()
    A.eq(core.text_width(""), 0)
    A.eq(core.text_width("hello"), 5)
    A.eq(core.text_width("héllo"), 5)
    A.eq(core.text_width("界"), 2)
    A.eq(core.text_width("a界b"), 4)
    A.eq(core.text_width("🚀"), 2)
    -- e + COMBINING ACUTE ACCENT (U+0301) occupies one cell.
    A.eq(core.text_width("e\204\129"), 1)
    A.eq(H.util.width("日本語"), 6)
    A.eq(H.util.width(""), 0)
  end)
end)

test("grid put, cell metadata and snapshot rows", function()
  H.with_core(12, 4, function()
    local nx = core.put(0, 0, "abc")
    A.eq(nx, 3)
    A.eq(core.snapshot()[1], "abc")

    local attrs = H.hl.attr.bold + H.hl.attr.underline
    core.put(1, 1, "B", 0x112233, 0x445566, attrs)
    local text, fg, bg, got_attrs, width = core.cell(1, 1)
    A.eq(text, "B")
    A.eq(fg, 0x112233)
    A.eq(bg, 0x445566)
    A.eq(got_attrs, attrs)
    A.eq(width, 1)

    local dtext, dfg, dbg, dattrs, dwidth = core.cell(0, 0)
    A.eq(dtext, "a")
    A.eq(dfg, -1)
    A.eq(dbg, -1)
    A.eq(dattrs, 0)
    A.eq(dwidth, 1)
    A.eq(core.cell(99, 0), nil)
  end)
end)

test("wide characters occupy two cells", function()
  H.with_core(10, 3, function()
    local nx = core.put(0, 0, "界x")
    A.eq(nx, 3)
    local text, _, _, _, width = core.cell(0, 0)
    A.eq(text, "界")
    A.eq(width, 2)
    local cont, _, _, _, cwidth = core.cell(1, 0)
    A.eq(cont, "")
    A.eq(cwidth, 0)
    A.eq(core.cell(2, 0), "x")
    A.eq(core.snapshot()[1], "界x")
    -- A wide glyph that would cross the right edge is not drawn.
    core.put(9, 1, "界")
    A.eq(core.snapshot()[2], "")
  end)
end)

test("clipping bounds grid writes", function()
  H.with_core(10, 5, function()
    core.clip(2, 2, 3, 1)
    core.put(0, 2, "abcdef")
    A.eq(core.snapshot()[3], "  cde")
    core.put(2, 3, "nope")
    A.eq(core.snapshot()[4], "")
    core.clip_reset()
    core.put(0, 4, "full")
    A.eq(core.snapshot()[5], "full")
  end)
end)

test("fill respects clipping and terminal bounds", function()
  H.with_core(8, 4, function()
    core.fill(0, 0, 8, 4, ".")
    for i = 1, 4 do
      A.eq(core.snapshot()[i], "........")
    end
    core.clear()
    core.clip(1, 1, 3, 2)
    core.fill(0, 0, 8, 4, "#")
    A.eq(core.snapshot()[1], "")
    A.eq(core.snapshot()[2], " ###")
    A.eq(core.snapshot()[3], " ###")
    A.eq(core.snapshot()[4], "")
  end)
end)

test("clear and resize rebuild the grid", function()
  H.with_core(10, 4, function()
    core.put(0, 0, "hello")
    core.clear()
    A.eq(core.snapshot()[1], "")
    core.resize(16, 6)
    local w, h = core.size()
    A.eq(w, 16)
    A.eq(h, 6)
    core.put(15, 5, "z")
    A.eq(core.snapshot()[6], "               z")
    A.eq(#core.rows(), 6)
    A.eq(#core.rows()[1], 16)
  end)
end)

test("rows preserve trailing blanks while snapshots trim", function()
  H.with_core(12, 2, function()
    core.put(0, 0, "hi")
    local rows = core.rows()
    A.eq(rows[1], "hi          ")
    A.eq(core.snapshot()[1], "hi")
  end)
end)

test("exit flag and ticks", function()
  H.with_core(8, 3, function()
    A.falsy(core.should_exit())
    local first = core.ticks()
    local second = core.ticks()
    A.ge(second, first)
    core.exit()
    A.truthy(core.should_exit())
  end)
end)

test("headless terminal helpers do not fail", function()
  H.with_core(10, 4, function()
    A.no_error(function()
      core.title("tuipro test")
      core.bell()
      core.copy("clipboard")
      core.set_mouse(false)
      core.set_paste(false)
      core.cursor(1, 1, true, "bar")
      core.cursor(-1, -1, false)
      core.put(0, 0, "x", 0xffffff, 0x000000, 0)
      core.flush()
    end)
  end)
end)

test("transparent highlights use the terminal default background", function()
  local hl = H.hl
  local opaque_normal = hl.bg("Normal")
  local opaque_selected = hl.bg("ListSelected")
  local ok, err = pcall(function()
    A.truthy(hl.set_transparent(true))
    A.eq(hl.bg("Normal"), hl.DEFAULT)
    A.eq(hl.bg("Button"), hl.DEFAULT)
    A.eq(hl.bg("StatusLine"), hl.DEFAULT)
    A.eq(hl.bg("NormalFloat"), hl.DEFAULT)
    -- Colored focus/selection backgrounds are preserved.
    A.ne(hl.bg("ListSelected"), hl.DEFAULT)
    A.eq(hl.bg("ListSelected"), opaque_selected)
    -- Named and inline neutral surfaces also become transparent.
    A.eq(hl.bg({ bg = "surface" }), hl.DEFAULT)
    A.eq(hl.bg({ bg = false }), hl.DEFAULT)
    A.ne(hl.bg({ bg = "accent" }), hl.DEFAULT)

    hl.set_transparent(false)
    A.eq(hl.bg("Normal"), opaque_normal)
    A.eq(hl.bg("ListSelected"), opaque_selected)
  end)
  hl.set_transparent(false)
  if not ok then
    error(err, 0)
  end
end)

return H.finish()
